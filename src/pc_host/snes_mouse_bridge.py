# src/pc_host/snes_mouse_bridge.py

import argparse
import sys
import time

import pygame
import serial

from bridge import BAUD_RATE, HEARTBEAT_SECONDS, open_controller
from serial_ports import resolve_serial_port

SYNC_1 = 0xAA
SYNC_MOUSE = 0x56

MOUSE_DEADZONE = 0.18
MOUSE_ANALOG_MAX_DELTA = 8
MOUSE_DPAD_DELTA = 4

# SNES Mouse second-byte layout (logical report, MSB first):
#   bit 7: right button
#   bit 6: left button
#   bits 5-4: hardware mouse speed/sensitivity state
#   bits 3-0: signature 0001
#
# Do not equate the hardware speed bits with the bridge's LOW/MEDIUM/HIGH
# cursor-speed setting. Authentic SNES Mouse sensitivity selection is a
# console-side Latch/Clock protocol operation and is intentionally separate.
SNES_MOUSE_SIGNATURE = 0x01
SNES_MOUSE_LEFT = 0x40
SNES_MOUSE_RIGHT = 0x80

SENSITIVITY_LOW = 0
SENSITIVITY_MEDIUM = 1
SENSITIVITY_HIGH = 2
SENSITIVITY_NAMES = ("LOW", "MEDIUM", "HIGH")
SENSITIVITY_SPEED_SCALE = (0.5, 1.0, 2.0)
DEFAULT_SENSITIVITY = SENSITIVITY_MEDIUM

# Keep the SNES Mouse speed bits at the exact known-good bring-up value for
# now. The bridge sensitivity controls below are a host-side cursor-speed
# feature. Authentic SNES Mouse sensitivity selection requires the console-side
# Latch/Clock command sequence and will be implemented independently.
SNES_MOUSE_WIRE_SPEED_BITS = 0


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Translate a connected gamepad into an emulated SNES Mouse. "
            "Initial target: Mario Paint on physical SNES hardware."
        )
    )
    parser.add_argument(
        "serial_port",
        nargs="?",
        metavar="COM_PORT",
        help=(
            "Optional Pico serial port override, for example COM3. "
            "If omitted, the active Pico is auto-detected."
        ),
    )
    parser.add_argument(
        "--port",
        dest="port_override",
        metavar="COM_PORT",
        help="Explicit Pico serial port override (same as positional COM_PORT).",
    )
    parser.add_argument(
        "--max-speed",
        type=int,
        default=MOUSE_ANALOG_MAX_DELTA,
        metavar="1..32",
        help=(
            "Maximum SNES mouse displacement generated by a full analog-stick "
            "tilt per console poll (default: 8)."
        ),
    )
    parser.add_argument(
        "--dpad-speed",
        type=int,
        default=MOUSE_DPAD_DELTA,
        metavar="1..32",
        help="SNES mouse displacement generated by held D-pad direction (default: 4).",
    )
    return parser.parse_args()


def clamp_speed(value, name):
    if value < 1 or value > 32:
        raise RuntimeError(f"{name} must be between 1 and 32.")
    return value


def init_controller():
    pygame.init()
    pygame.joystick.init()

    if pygame.joystick.get_count() == 0:
        raise RuntimeError("No controller detected.")

    return open_controller(0)


def snes_bit_is_pressed(joystick, button_map, target_bit):
    num_buttons = joystick.get_numbuttons()
    for button_index, snes_bit in button_map.items():
        if snes_bit != target_bit or button_index >= num_buttons:
            continue
        if joystick.get_button(button_index):
            return True
    return False


def read_sensitivity_controls(joystick, button_map):
    """Return (decrease, increase) using canonical SNES control positions."""
    decrease = (
        snes_bit_is_pressed(joystick, button_map, 10)  # L shoulder
        or snes_bit_is_pressed(joystick, button_map, 1)  # Y face
    )
    increase = (
        snes_bit_is_pressed(joystick, button_map, 11)  # R shoulder
        or snes_bit_is_pressed(joystick, button_map, 9)  # X face
    )
    return decrease, increase


def scaled_speed(base_speed, sensitivity):
    scale = SENSITIVITY_SPEED_SCALE[sensitivity]
    return max(1, int(round(base_speed * scale)))


def read_dpad(joystick, button_map):
    up = snes_bit_is_pressed(joystick, button_map, 4)
    down = snes_bit_is_pressed(joystick, button_map, 5)
    left = snes_bit_is_pressed(joystick, button_map, 6)
    right = snes_bit_is_pressed(joystick, button_map, 7)

    if joystick.get_numhats() > 0:
        hat_x, hat_y = joystick.get_hat(0)
        up = up or hat_y == 1
        down = down or hat_y == -1
        left = left or hat_x == -1
        right = right or hat_x == 1

    x = (-1 if left else 0) + (1 if right else 0)
    y = (-1 if up else 0) + (1 if down else 0)
    return x, y


def axis_to_delta(value, max_delta):
    magnitude = abs(value)
    if magnitude <= MOUSE_DEADZONE:
        return 0

    normalized = (magnitude - MOUSE_DEADZONE) / (1.0 - MOUSE_DEADZONE)
    delta = max(1, int(round(normalized * max_delta)))
    return -delta if value < 0.0 else delta


def read_analog_motion(joystick, directional_axis_pairs, max_delta):
    if not directional_axis_pairs:
        return 0, 0

    # For ordinary modern pads the first calibrated pair is the left stick.
    # Arcade controllers that expose a lever as an analog pair use this same
    # first pair. Additional pairs (for example a right stick) are deliberately
    # ignored in this first mouse-emulation proof.
    axis_x_index, axis_y_index = directional_axis_pairs[0]
    if (
        axis_x_index >= joystick.get_numaxes()
        or axis_y_index >= joystick.get_numaxes()
    ):
        return 0, 0

    return (
        axis_to_delta(joystick.get_axis(axis_x_index), max_delta),
        axis_to_delta(joystick.get_axis(axis_y_index), max_delta),
    )


def encode_sign_magnitude(delta):
    delta = max(-127, min(127, int(delta)))
    magnitude = abs(delta)
    sign = 0x80 if delta < 0 else 0x00
    return sign | magnitude


def build_logical_mouse_report(
    joystick,
    button_map,
    directional_axis_pairs,
    max_speed,
    dpad_speed,
    sensitivity,
):
    pygame.event.pump()

    analog_speed = scaled_speed(max_speed, sensitivity)
    digital_speed = scaled_speed(dpad_speed, sensitivity)

    analog_x, analog_y = read_analog_motion(
        joystick,
        directional_axis_pairs,
        analog_speed,
    )
    dpad_x, dpad_y = read_dpad(joystick, button_map)

    # Analog stick/lever is the primary motion source. A D-pad direction can
    # still add a fixed-rate contribution, which also supports digital-only
    # controllers and arcade-stick DP modes.
    dx = max(-127, min(127, analog_x + (dpad_x * digital_speed)))
    dy = max(-127, min(127, analog_y + (dpad_y * digital_speed)))

    # Preserve the canonical SNES face positions already encoded in each
    # controller profile: SNES B position -> mouse left, SNES A position ->
    # mouse right. This makes the mapping controller-independent.
    left_pressed = snes_bit_is_pressed(joystick, button_map, 0)
    right_pressed = snes_bit_is_pressed(joystick, button_map, 8)

    second_byte = (
        SNES_MOUSE_SIGNATURE
        | ((SNES_MOUSE_WIRE_SPEED_BITS & 0x03) << 4)
        | (SNES_MOUSE_LEFT if left_pressed else 0)
        | (SNES_MOUSE_RIGHT if right_pressed else 0)
    )

    # SNES Mouse motion is sign-and-magnitude. Y sign=1 means up; X sign=1
    # means left, matching negative Pygame axis movement for both coordinates.
    y_byte = encode_sign_magnitude(dy)
    x_byte = encode_sign_magnitude(dx)

    logical_report = (
        (0x00 << 24)
        | (second_byte << 16)
        | (y_byte << 8)
        | x_byte
    )

    return (
        logical_report,
        dx,
        dy,
        left_pressed,
        right_pressed,
        analog_speed,
        digital_speed,
    )


def logical_report_to_wire_word(logical_report):
    """Convert logical MSB-first mouse bits to proven physical-wire ordering."""
    wire_word = 0

    for serial_index in range(32):
        logical_bit = (logical_report >> (31 - serial_index)) & 1

        # The proven PAL-SNES adapter path presents logical 1 as physical LOW
        # and logical 0 as physical HIGH at the Pico-side DATA output.
        physical_bit = 0 if logical_bit else 1
        wire_word |= physical_bit << serial_index

    return wire_word


def build_mouse_packet(wire_word):
    return bytes((
        SYNC_1,
        SYNC_MOUSE,
        wire_word & 0xFF,
        (wire_word >> 8) & 0xFF,
        (wire_word >> 16) & 0xFF,
        (wire_word >> 24) & 0xFF,
    ))


def send_mouse_report(serial_port, logical_report):
    wire_word = logical_report_to_wire_word(logical_report)
    packet = build_mouse_packet(wire_word)
    bytes_written = serial_port.write(packet)

    if bytes_written != len(packet):
        raise serial.SerialException(
            f"Short serial write: expected {len(packet)} bytes, wrote {bytes_written}"
        )

    serial_port.flush()
    return packet, wire_word


def build_neutral_report():
    second_byte = (
        SNES_MOUSE_SIGNATURE
        | ((SNES_MOUSE_WIRE_SPEED_BITS & 0x03) << 4)
    )
    return (0x00 << 24) | (second_byte << 16)


def send_neutral(serial_port):
    neutral_report = build_neutral_report()
    for _ in range(5):
        send_mouse_report(serial_port, neutral_report)
        time.sleep(0.005)


def main():
    args = parse_args()
    joystick = None
    serial_port = None

    try:
        max_speed = clamp_speed(args.max_speed, "--max-speed")
        dpad_speed = clamp_speed(args.dpad_speed, "--dpad-speed")
        sensitivity = DEFAULT_SENSITIVITY
        previous_decrease = False
        previous_increase = False

        joystick, button_map, directional_axis_pairs = init_controller()

        if (
            args.serial_port
            and args.port_override
            and args.serial_port.casefold() != args.port_override.casefold()
        ):
            raise RuntimeError(
                "Conflicting serial ports supplied: "
                f"{args.serial_port} and {args.port_override}"
            )

        serial_device = resolve_serial_port(args.port_override or args.serial_port)
        serial_port = serial.Serial(
            serial_device,
            BAUD_RATE,
            timeout=0,
            write_timeout=0.100,
        )

        print(f"SNES Mouse bridge streaming to {serial_device}. Press Ctrl+C to exit.")
        print(
            "Mapping: left stick/lever or D-pad -> mouse motion; "
            "SNES B position -> LEFT click; SNES A position -> RIGHT click."
        )
        print(
            f"Motion tuning base: analog max={max_speed}, D-pad speed={dpad_speed}, "
            f"deadzone={MOUSE_DEADZONE:.2f}"
        )
        print(
            "Sensitivity controls: L or Y = decrease; R or X = increase. "
            "Each press changes one step."
        )
        print(
            f"Bridge sensitivity: {SENSITIVITY_NAMES[sensitivity]} "
            f"({sensitivity})"
        )
        print(
            "SNES Mouse button report: known-good compatibility mode; "
            "B=MouseLeft, A=MouseRight."
        )

        active_instance_id = joystick.get_instance_id()
        last_report = None
        last_send_time = 0.0
        last_reconnect_poll = 0.0

        while True:
            now = time.monotonic()

            for event in pygame.event.get():
                if (
                    event.type == pygame.JOYDEVICEREMOVED
                    and joystick is not None
                    and event.instance_id == active_instance_id
                ):
                    print(
                        "Controller disconnected/re-enumerating. "
                        "Sending neutral SNES Mouse state and waiting..."
                    )
                    send_neutral(serial_port)
                    try:
                        joystick.quit()
                    except pygame.error:
                        pass
                    joystick = None
                    button_map = None
                    directional_axis_pairs = ()
                    active_instance_id = None
                    previous_decrease = False
                    previous_increase = False
                    last_report = build_neutral_report()
                    last_send_time = time.monotonic()
                    last_reconnect_poll = 0.0

                elif event.type == pygame.JOYDEVICEADDED and joystick is None:
                    try:
                        joystick, button_map, directional_axis_pairs = open_controller(
                            event.device_index
                        )
                        active_instance_id = joystick.get_instance_id()
                        last_report = None
                        last_send_time = 0.0
                        print("Controller re-enumerated. SNES Mouse bridge resumed.")
                    except pygame.error as err:
                        print(f"Controller re-open deferred: {err}")
                        joystick = None

            if joystick is None:
                if (now - last_reconnect_poll) >= 0.050:
                    last_reconnect_poll = now
                    if pygame.joystick.get_count() > 0:
                        try:
                            joystick, button_map, directional_axis_pairs = open_controller(0)
                            active_instance_id = joystick.get_instance_id()
                            last_report = None
                            last_send_time = 0.0
                            print("Controller rediscovered. SNES Mouse bridge resumed.")
                        except pygame.error:
                            joystick = None

                if joystick is None and (now - last_send_time) >= HEARTBEAT_SECONDS:
                    send_mouse_report(serial_port, build_neutral_report())
                    last_send_time = now

                if joystick is None:
                    time.sleep(0.005)
                    continue

            try:
                decrease_pressed, increase_pressed = read_sensitivity_controls(
                    joystick,
                    button_map,
                )

                decrease_edge = decrease_pressed and not previous_decrease
                increase_edge = increase_pressed and not previous_increase

                if decrease_edge and not increase_edge:
                    old_sensitivity = sensitivity
                    sensitivity = max(SENSITIVITY_LOW, sensitivity - 1)
                    if sensitivity != old_sensitivity:
                        print(
                            f"Sensitivity: {SENSITIVITY_NAMES[old_sensitivity]} "
                            f"-> {SENSITIVITY_NAMES[sensitivity]}"
                        )
                    else:
                        print("Sensitivity already at LOW.")

                elif increase_edge and not decrease_edge:
                    old_sensitivity = sensitivity
                    sensitivity = min(SENSITIVITY_HIGH, sensitivity + 1)
                    if sensitivity != old_sensitivity:
                        print(
                            f"Sensitivity: {SENSITIVITY_NAMES[old_sensitivity]} "
                            f"-> {SENSITIVITY_NAMES[sensitivity]}"
                        )
                    else:
                        print("Sensitivity already at HIGH.")

                previous_decrease = decrease_pressed
                previous_increase = increase_pressed

                (
                    report,
                    dx,
                    dy,
                    left_pressed,
                    right_pressed,
                    analog_speed,
                    digital_speed,
                ) = build_logical_mouse_report(
                    joystick,
                    button_map,
                    directional_axis_pairs,
                    max_speed,
                    dpad_speed,
                    sensitivity,
                )
            except pygame.error:
                print(
                    "Controller vanished during sampling. "
                    "Sending neutral SNES Mouse state and waiting..."
                )
                send_neutral(serial_port)
                try:
                    joystick.quit()
                except pygame.error:
                    pass
                joystick = None
                button_map = None
                directional_axis_pairs = ()
                active_instance_id = None
                previous_decrease = False
                previous_increase = False
                last_report = build_neutral_report()
                last_send_time = time.monotonic()
                last_reconnect_poll = 0.0
                continue

            now = time.monotonic()
            if report != last_report or (now - last_send_time) >= HEARTBEAT_SECONDS:
                packet, wire_word = send_mouse_report(serial_port, report)
                last_send_time = now
            else:
                packet = None
                wire_word = None

            if report != last_report:
                packet_hex = " ".join(f"{byte:02X}" for byte in packet)
                print(
                    f"Mouse dx={dx:+d} dy={dy:+d} "
                    f"L={int(left_pressed)} R={int(right_pressed)} "
                    f"bridge-sens={SENSITIVITY_NAMES[sensitivity]}({sensitivity}) "
                    f"speed={analog_speed}/{digital_speed} "
                    f"report=0x{report:08X} wire=0x{wire_word:08X} "
                    f"TX={packet_hex}"
                )
                last_report = report

            time.sleep(0.001)

    except KeyboardInterrupt:
        print("\nCtrl+C received. Releasing SNES Mouse state...")

    except serial.SerialTimeoutException:
        print("\nSerial write timed out. Releasing bridge.")

    except (serial.SerialException, RuntimeError) as err:
        print(f"SNES Mouse bridge error: {err}")

    finally:
        if serial_port is not None:
            try:
                send_neutral(serial_port)
            except (serial.SerialException, serial.SerialTimeoutException):
                pass
            try:
                serial_port.close()
            except serial.SerialException:
                pass

        pygame.quit()
        print("SNES Mouse bridge stopped.")


if __name__ == "__main__":
    main()
